
    
// Program for string manipulation

class StringDemo {
    public static void main(String args[]) {

        String s1 = "Hello";
        String s2 = "World";

        // concatenation
        String s3 = s1 + " " + s2;

        System.out.println("String = " + s3);

        // length of string
        System.out.println("Length = " + s3.length());

        // uppercase conversion
        System.out.println("Uppercase = " + s3.toUpperCase());
    }
}
